ALTER TABLE pago MODIFY metodo_pago VARCHAR2(20);
ALTER TABLE pago ADD CONSTRAINT chk_pago_metodo CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA'));

-- Regla 3: Eliminar columna edad de PACIENTE y agregar fecha_nacimiento
ALTER TABLE paciente DROP COLUMN edad;
