-- 1. Tabla REGION
CREATE TABLE REGION (
    id_region     NUMBER(3) NOT NULL,
    nombre_region VARCHAR2(50) NOT NULL,
    CONSTRAINT region_pk PRIMARY KEY (id_region)
);

-- 2. Tabla COMUNA
CREATE TABLE COMUNA (
    id_comuna     NUMBER(5) NOT NULL,
    id_region     NUMBER(3) NOT NULL,
    nombre_comuna VARCHAR2(50) NOT NULL,
    CONSTRAINT comuna_pk PRIMARY KEY (id_comuna),
    CONSTRAINT comuna_region_fk FOREIGN KEY (id_region) REFERENCES REGION (id_region)
);

-- 3. Tabla ASOCIACION
-- Condición: Fecha de creación igual o posterior al 31/12/1980
CREATE TABLE ASOCIACION (
    id_asociacion     NUMBER(4) NOT NULL,
    nombre_asociacion VARCHAR2(60) NOT NULL,
    fecha_creacion    DATE NOT NULL,
    tipo_asociacion   CHAR(1) NOT NULL,
    CONSTRAINT asociacion_pk PRIMARY KEY (id_asociacion),
    CONSTRAINT asociacion_fecha_ck CHECK (fecha_creacion >= TO_DATE('31/12/1980', 'DD/MM/YYYY')),
    CONSTRAINT asociacion_tipo_ck CHECK (tipo_asociacion IN ('P', 'A'))
);

-- 4. Tabla NACIONALIDAD
-- Condición: Clave primaria IDENTITY que inicia en 210 e incrementa de 2 en 2
CREATE TABLE NACIONALIDAD (
    id_nacion   NUMBER(5) GENERATED BY DEFAULT AS IDENTITY (START WITH 210 INCREMENT BY 2) NOT NULL,
    descripcion VARCHAR2(50) NOT NULL,
    CONSTRAINT nacionalidad_pk PRIMARY KEY (id_nacion)
);

-- 5. Tabla CLUB_FUTBOL
-- Condición: Nombre del club debe ser único
CREATE TABLE CLUB_FUTBOL (
    id_club         NUMBER(4) NOT NULL,
    nombre_club     VARCHAR2(60) NOT NULL,
    patrimonio      NUMBER(15) NOT NULL,
    ubicacion_calle VARCHAR2(100) NOT NULL,
    tipo_club       VARCHAR2(20) NOT NULL,
    CONSTRAINT club_futbol_pk PRIMARY KEY (id_club),
    CONSTRAINT club_nombre_un UNIQUE (nombre_club)
);

-- 6. Secuencia para la tabla CLUB_FUTBOL
-- Condición: Comienza en 703 e incrementa de 4 en 4
CREATE SEQUENCE SEQ_CLUB_FUTBOL
    START WITH 703
    INCREMENT BY 4
    NOCACHE;

-- 7. Tabla IDIOMA
CREATE TABLE IDIOMA (
    id_idioma     NUMBER(4) NOT NULL,
    nombre_idioma VARCHAR2(30) NOT NULL,
    CONSTRAINT idioma_pk PRIMARY KEY (id_idioma)
);

-- 8. Tabla ESCUELA_FORMATIVA
CREATE TABLE ESCUELA_FORMATIVA (
    id_escuela     NUMBER(6) NOT NULL,
    nombre_escuela VARCHAR2(60) NOT NULL,
    capacidad      NUMBER(6) NOT NULL,
    fecha_fundacion DATE NOT NULL,
    CONSTRAINT escuela_formativa_pk PRIMARY KEY (id_escuela)
);

-- 9. Tabla TRABAJADOR
CREATE TABLE TRABAJADOR (
    cod_inscripcion  NUMBER(8) NOT NULL,
    numrun           NUMBER(8) NOT NULL,
    dvrun            VARCHAR2(1) NOT NULL,
    primer_nombre    VARCHAR2(30) NOT NULL,
    segundo_nombre   VARCHAR2(30),
    apellido_paterno VARCHAR2(30) NOT NULL,
    apellido_materno VARCHAR2(30) NOT NULL,
    sueldo_base      NUMBER(10) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    genero           CHAR(1) NOT NULL,
    estado_civil     VARCHAR2(20) NOT NULL,
    fono_movil       VARCHAR2(15) NOT NULL,
    direccion        VARCHAR2(100) NOT NULL,
    id_comuna        NUMBER(5) NOT NULL,
    id_nacion        NUMBER(5) NOT NULL,
    CONSTRAINT trabajador_pk PRIMARY KEY (cod_inscripcion),
    CONSTRAINT trabajador_run_un UNIQUE (numrun),
    CONSTRAINT trabajador_comuna_fk FOREIGN KEY (id_comuna) REFERENCES COMUNA (id_comuna),
    CONSTRAINT trabajador_nacionalidad_fk FOREIGN KEY (id_nacion) REFERENCES NACIONALIDAD (id_nacion)
);

-- 10. Tabla JUGADOR (Subtipo de TRABAJADOR)
CREATE TABLE JUGADOR (
    cod_inscripcion    NUMBER(8) NOT NULL,
    puesto_campo       VARCHAR2(30) NOT NULL,
    monto_acum_premios NUMBER(12) NOT NULL,
    ano_retiro_amateur NUMBER(4),
    id_escuela         NUMBER(6),
    id_asociacion      NUMBER(4) NOT NULL,
    CONSTRAINT jugador_pk PRIMARY KEY (cod_inscripcion),
    CONSTRAINT jugador_trabajador_fk FOREIGN KEY (cod_inscripcion) REFERENCES TRABAJADOR (cod_inscripcion),
    CONSTRAINT jugador_escuela_fk FOREIGN KEY (id_escuela) REFERENCES ESCUELA_FORMATIVA (id_escuela),
    CONSTRAINT jugador_asociacion_fk FOREIGN KEY (id_asociacion) REFERENCES ASOCIACION (id_asociacion)
);

-- 11. Tabla PERSONAL_PLANTA (Subtipo de TRABAJADOR)
CREATE TABLE PERSONAL_PLANTA (
    cod_inscripcion NUMBER(8) NOT NULL,
    hrs_trabajadas  NUMBER(3),
    valor_hrs_extras NUMBER(8),
    CONSTRAINT personal_planta_pk PRIMARY KEY (cod_inscripcion),
    CONSTRAINT personal_planta_trabajador_fk FOREIGN KEY (cod_inscripcion) REFERENCES TRABAJADOR (cod_inscripcion)
);

-- 12. Tabla PERMANENCIA_CLUB
CREATE TABLE PERMANENCIA_CLUB (
    id_permanencia  NUMBER(8) NOT NULL,
    cod_inscripcion NUMBER(8) NOT NULL,
    id_club         NUMBER(4) NOT NULL,
    fecha_inicio    DATE NOT NULL,
    fecha_fin       DATE,
    CONSTRAINT permanencia_club_pk PRIMARY KEY (id_permanencia),
    CONSTRAINT permanencia_jugador_fk FOREIGN KEY (cod_inscripcion) REFERENCES JUGADOR (cod_inscripcion),
    CONSTRAINT permanencia_club_fk FOREIGN KEY (id_club) REFERENCES CLUB_FUTBOL (id_club)
);

-- 13. Tabla DOMINIO_IDIOMA
CREATE TABLE DOMINIO_IDIOMA (
    id_dominio      NUMBER(8) NOT NULL,
    cod_inscripcion NUMBER(8) NOT NULL,
    id_idioma       NUMBER(4) NOT NULL,
    nivel_dominio   VARCHAR2(20) NOT NULL,
    CONSTRAINT dominio_idioma_pk PRIMARY KEY (id_dominio),
    CONSTRAINT dominio_jugador_fk FOREIGN KEY (cod_inscripcion) REFERENCES JUGADOR (cod_inscripcion),
    CONSTRAINT dominio_idioma_fk FOREIGN KEY (id_idioma) REFERENCES IDIOMA (id_idioma)
);


